export const LANGS = Object.keys(DICTS) as Lang[];

function match(tag: string): Lang | null {
  const lower = tag.toLowerCase();
  const base = lower.split(/[-_]/)[0];
  if (base === "zh") {
    const traditional = /hant|tw|hk|mo/.test(lower);
    return traditional ? "zh-Hant" : "zh-Hans";
  }
  const hit = LANGS.find((l) => l === base);
  return hit ?? null;
}

/** The language to draw in: the chosen one, else the browser's first match. */
export function resolveLang(choice: string): Lang {
  if (choice && choice !== "auto") {
    const exact = LANGS.find((l) => l === choice);
    if (exact) return exact;
  }
  const tags =
    typeof navigator !== "undefined" && navigator.languages?.length
      ? navigator.languages
      : [typeof navigator !== "undefined" ? navigator.language : "en"];
  for (const tag of tags) {
    const h = match(tag ?? "");
    if (h) return h;
  }
  return "en";
}

export function localeOf(lang: Lang, choice: string = lang): string {
  if (choice === "auto" && typeof navigator !== "undefined") {
    for (const tag of navigator.languages?.length ? navigator.languages : [navigator.language]) {
      if (tag && match(tag) === lang) return tag;
    }
  }
  return LOCALES[lang];
}

export function t(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const template = DICTS[lang]?.[key] ?? EN[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    vars[name] === undefined ? m : String(vars[name]),
  );
}
