// Regenerates src/data/zoneCountries.ts from IANA's zone.tab and backward
// links. Usage: node tools/gen-zone-countries.mjs [path-to-tzdb-data-dir]
// The two files are in the public-domain tzdb distribution (or the system's
// /usr/share/zoneinfo); the country code picks each zone's local language.

import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const country = new Map();
for (const line of fs.readFileSync(path.join(dir, "zone.tab"), "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [cc, , zone] = line.split("\t");
  if (zone) country.set(zone, cc);
}
// The links that keep old spellings alive are listed before the links they
// point at (Asmara, Pohnpei, Chuuk are themselves links), so a plain map would
// stop at the first hop. Resolve each spelling to a zone zone.tab knows.
const aliases = new Map();
for (const line of fs.readFileSync(path.join(dir, "backward"), "utf8").split("\n")) {
  if (!line.startsWith("Link")) continue;
  const [, target, name] = line.split(/\s+/);
  if (!name) continue;
  // A few links exist only for the old spelling of a zone (Asmera for
  // Asmara); their `#=` comment names the zone the place is really in.
  aliases.set(name, line.match(/#=\s*(\S+)/)?.[1] ?? target);
}
const resolve = (zone) => {
  let cur = zone;
  for (let i = 0; i < 8 && !country.has(cur); i++) {
    const next = aliases.get(cur);
    if (!next) break;
    cur = next;
  }
  return cur;
};
const zones = new Set(Intl.supportedValuesOf("timeZone"));
for (const [, id] of JSON.parse(fs.readFileSync("src/data/cities.json", "utf8"))) zones.add(id);

const out = {};
const missing = [];
for (const zone of [...zones].sort()) {
  const cc = country.get(zone) ?? country.get(resolve(zone));
  if (cc) out[zone] = cc;
  else missing.push(zone);
}
if (missing.length) {
  console.error(`No country for ${missing.length} zone(s): ${missing.join(", ")}`);
  process.exitCode = 1;
}

const body = Object.entries(out)
  .map(([zone, cc]) => `  ${JSON.stringify(zone)}: ${JSON.stringify(cc)},`)
  .join("\n");
fs.writeFileSync(
  "src/data/zoneCountries.ts",
  `// Which country each zone belongs to, from IANA's zone.tab, with legacy
// spellings resolved through its backward links. The country picks the
// language a zone's own name is written in. Generated by
// tools/gen-zone-countries.mjs: do not edit by hand.

export const ZONE_COUNTRY: Record<string, string> = {
${body}
};
`,
);
console.log(`Wrote ${Object.keys(out).length} zones to src/data/zoneCountries.ts`);
